// Dependency-free, deterministic JSON Schema -> TypeScript contract generator.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = dirname(fileURLToPath(import.meta.url));
const files = readdirSync(join(root, 'schemas')).filter(n => n.endsWith('.schema.json')).sort();
const schemas = new Map(files.map(file => [file, JSON.parse(readFileSync(join(root, 'schemas', file), 'utf8'))]));
const main = { 'knowledge-ir.schema.json': 'KnowledgeIr', 'style.schema.json': 'StyleSpec', 'project.schema.json': 'Project', 'task-envelope.schema.json': 'TaskEnvelope', 'result-envelope.schema.json': 'ResultEnvelope' };
const aliases = { id: 'Id', source: 'SourceFile', anchor: 'SourceAnchor', node: 'KnowledgeNode', edge: 'GraphEdge', correction: 'Correction', unverified: 'UnverifiedItem', point: 'Point', rect: 'Rect', textLine: 'TextLine', placedNode: 'PlacedNode', placedEdge: 'PlacedEdge', placedGroup: 'PlacedGroup', layoutPage: 'LayoutPage', layout: 'LayoutDocument', finding: 'Finding', validation: 'ValidationReport', artifacts: 'ArtifactPaths', taskVersion: 'TaskVersion', task: 'Task', audit: 'AuditEvent', settings: 'ProjectSettings' };
function type(schema, owner) {
  if (schema.$ref) {
    const [file, fragment] = schema.$ref.split('#');
    if (!fragment) return main[file || owner];
    if (!fragment.startsWith('/$defs/')) throw Error(`Unsupported reference ${schema.$ref}`);
    return aliases[fragment.slice('/$defs/'.length)];
  }
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(s => type(s, owner)).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(t => type({ ...schema, type: t }, owner)).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `Array<${type(schema.items ?? {}, owner)}>`;
    case 'object': {
      if (!schema.properties) return `Record<string, ${schema.additionalProperties && typeof schema.additionalProperties === 'object' ? type(schema.additionalProperties, owner) : 'unknown'}>`;
      return `{\n${Object.entries(schema.properties).map(([key, value]) => `  ${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${type(value, owner)};`).join('\n')}\n}`;
    }
    default: throw Error(`Unsupported schema in ${owner}: ${JSON.stringify(schema)}`);
  }
}
const sha = content => createHash('sha256').update(content).digest('hex');
const schemaBytes = files.map(file => `${file}\n${readFileSync(join(root, 'schemas', file), 'utf8')}\n`).join('');
let output = `// Generated by node packages/contracts/generate.mjs; do not edit.\n// Schema SHA-256: ${sha(schemaBytes)}\n\n`;
for (const [file, schema] of schemas) {
  output += `export type ${main[file]} = ${type(schema, file)};\n\n`;
  for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
    if (!aliases[name]) throw Error(`Missing export alias for ${file} ${name}`);
    output += `export type ${aliases[name]} = ${type(definition, file)};\n\n`;
  }
}
output = output.trimEnd() + '\n';
const manifest = JSON.stringify({ schema_sha256: sha(schemaBytes), types_sha256: sha(output) }, null, 2) + '\n';
for (const [file, content] of [['types.ts', output], ['manifest.json', manifest]]) {
  const path = join(root, 'generated', file);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) { process.stderr.write(`Contract drift: ${path}\n`); process.exitCode = 1; }
  } else writeFileSync(path, content);
}
