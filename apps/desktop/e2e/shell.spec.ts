import { expect, test } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('compact shell keeps real browser tasks, keyboard menus, drafts and settings working', async ({ page }) => {
  test.setTimeout(120_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('/tmp/entwurf-titlebar-qa', { recursive: true });
  await page.goto('./');
  await expect(page.getByRole('heading', { name: '浏览器项目', exact: true })).toBeVisible();
  await expect(page.locator('.breadcrumb')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '关闭窗口', exact: true })).toHaveCount(0);
  await page.getByLabel('项目名称', { exact: true }).fill('概率论 · 真实浏览器工作区');
  await page.getByRole('button', { name: '新建项目', exact: true }).click();
  await expect(page.getByText('创建项目完成', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '新建任务', exact: true }).click();
  await expect(page.getByLabel('任务标题', { exact: true })).toBeFocused();
  await page.getByLabel('任务标题', { exact: true }).fill('随机事件与样本空间');
  await page.getByLabel('章节（可选）', { exact: true }).fill('第一章 概率基础');
  await page.getByRole('button', { name: '创建任务', exact: true }).click();
  await expect(page.getByRole('heading', { name: '导入资料', exact: true })).toBeVisible();
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '选择本机文件并导入', exact: true }).click();
  await (await chooser).setFiles({ name: 'shell-public.md', mimeType: 'text/markdown', buffer: Buffer.from('# 概率论\n\n## 随机事件\n样本空间包含全部可能结果。事件是样本空间的子集。\n') });
  await expect(page.getByText('导入资料完成', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '切换到任务 随机事件与样本空间', exact: true }).click();
  await expect(page.getByRole('heading', { name: '任务与图片', exact: true })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: '结果', exact: true }).click();
  await page.getByRole('textbox', { name: '节点正文', exact: true }).fill('保存于真实浏览器数据库的公开编辑。');
  await expect(page.getByRole('button', { name: '新建任务', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '后退', exact: true }).click();
  await page.getByRole('button', { name: '前进', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '节点正文', exact: true })).toHaveValue('保存于真实浏览器数据库的公开编辑。');
  await page.getByRole('button', { name: '编辑', exact: true }).click();
  await page.getByRole('menuitem', { name: '保存节点修改', exact: true }).click();
  await expect(page.getByText('保存节点完成', { exact: true })).toBeVisible();
  await page.getByRole('navigation').getByRole('button', { name: '项目', exact: true }).click();
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/desktop-dark.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '文件', exact: true }).click();
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/menu-dark.png', fullPage: false, animations: 'disabled' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: '文件', exact: true })).toBeFocused();
  await page.getByRole('button', { name: '打开设置', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '任务侧栏' })).toHaveCount(0);
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/settings-dark.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '切换到浅色主题', exact: true }).click();
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/settings-light.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '切换任务侧栏', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '任务侧栏' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: '切换到任务 随机事件与样本空间', exact: true })).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '切换任务侧栏', exact: true }).click();
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/mobile-light.png', fullPage: false, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.getByRole('button', { name: '切换任务侧栏', exact: true }).click();
  await page.screenshot({ path: '/tmp/entwurf-titlebar-qa/mobile-tasks.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '切换到任务 随机事件与样本空间', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '任务侧栏' })).toHaveCount(0);
  expect(errors).toEqual([]);
});
