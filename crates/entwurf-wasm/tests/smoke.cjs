const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const modulePath = process.env.ENTWURF_WASM_NODE || path.join(__dirname, '../pkg-node/entwurf_wasm.js');
assert.ok(fs.existsSync(modulePath), 'real compiled browser Workspace WASM module must exist');
const api = require(modulePath);
const encode = value => new TextEncoder().encode(value);
const call = (command, args = {}) => JSON.parse(api.browser_call(command, JSON.stringify(args)));
api.browser_reset();
assert.throws(() => api.browser_put_file('../escape.md', encode('bad')), /absolute|path/);
assert.throws(() => api.browser_put_file('/projects/../escape.md', encode('bad')), /parent|path/);
call('create_project', {root:'/projects/smoke', name:'浏览器持久项目'});
let snap = call('create_task', {title:'Portable knowledge'});
const taskId = snap.selected_task_id;
const source = '# Conservation\n\nEnergy is conserved in an isolated system.\n';
const latex = '\\section{Momentum}\nMomentum is conserved.\n\\[p=mv\\]\n';
api.browser_put_file('/uploads/source.md', encode(source));
api.browser_put_file('/uploads/source.tex', encode(latex));
snap = call('import_sources', {taskId, paths:['/uploads/source.md','/uploads/source.tex']});
assert.equal(snap.current_version.ir.sources.length, 2);
assert.ok(snap.current_version.ir.nodes.length > 1);
while (snap.current_version.ir.unverified.length) {
  snap = call('resolve_review', {taskId, baseVersionId:snap.current_version.id, itemId:snap.current_version.ir.unverified[0].id, note:'Checked against the retained source.'});
}
snap = call('preview_current', {taskId});
assert.ok(snap.preview_pages.length > 0, JSON.stringify(snap.current_version.validation));
assert.ok(snap.preview_pages[0].svg.includes('<svg'));
snap = call('export_current', {taskId});
assert.equal(snap.project.tasks[0].state, 'EXPORTED', JSON.stringify(snap.current_version.validation));
const {svg,png,pdf,manifest,ir} = snap.current_version.artifacts;
assert.ok(new TextDecoder().decode(api.browser_get_file(svg[0])).includes('<svg'));
assert.deepEqual([...api.browser_get_file(png[0]).slice(0,8)], [137,80,78,71,13,10,26,10]);
assert.equal(new TextDecoder().decode(api.browser_get_file(pdf).slice(0,5)), '%PDF-');
assert.ok(JSON.parse(new TextDecoder().decode(api.browser_get_file(manifest))).files.length > 3);
assert.equal(call('artifact_path',{taskId,kind:'pdf'}),pdf);
assert.equal(JSON.parse(new TextDecoder().decode(api.browser_get_file(ir))).task_id, taskId);
call('prepare_handoff', {taskId});
const files = JSON.parse(api.browser_list_files()).map(p => [p, api.browser_get_file(p)]);
api.browser_reset();
for (const [p,b] of files) api.browser_put_file(p,b);
snap = call('load_existing_project', {root:'/projects/smoke'});
assert.equal(snap.project.name, '浏览器持久项目');
assert.ok(snap.handoff.markdown.length > 0);
const retained = snap.current_version.ir.sources.find(s => s.original_name === 'source.md');
assert.equal(new TextDecoder().decode(api.browser_get_file(retained.stored_path)), source);
api.browser_put_file(retained.stored_path, encode('tampered'));
snap = call('preview_current', {taskId});
assert.ok(snap.current_version.validation.findings.some(f => f.code === 'source_integrity' && f.severity === 'blocking'));
assert.equal(snap.preview_pages.length, 0);
console.log('WASM real Workspace: MD + TeX review, SVG/PNG/PDF export, retained state reopen, source tamper rejection PASS');
// Extraction is a platform boundary; core binds transcript bytes to retained original bytes.
const crypto = require('node:crypto');
const pixels = new Uint8Array(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a7b8AAAAASUVORK5CYII=', 'base64'));
api.browser_put_file('/uploads/image.png', pixels);
const extraction = {schema_version:1,source_sha256:crypto.createHash('sha256').update(pixels).digest('hex'),source_kind:'image',page_count:1,pages:[{page:null,text:'Measured value is 7.\n',engine:'tesseract.js',is_ocr:true,region:{left:0,top:0,width:1,height:1,unit:'pixels'}}],diagnostics:[]};
assert.throws(() => call('register_extraction',{path:'/uploads/image.png',extraction:{...extraction,source_sha256:'0'.repeat(64)}}), /hash|SHA/);
call('register_extraction',{path:'/uploads/image.png',extraction});
snap = call('create_task',{title:'Extracted image'});
const imageTask = snap.selected_task_id;
snap = call('import_sources',{taskId:imageTask,paths:['/uploads/image.png']});
assert.ok(snap.current_version.ir.unverified.some(item => item.kind === 'ocr'));
assert.ok(snap.current_version.ir.sources[0].notes.some(note => note.startsWith('ingestion_transcript:') && note.includes('tesseract.js')));
assert.equal(snap.current_version.ir.nodes[0].anchors[0].region.unit,'pixels');
console.log('WASM extraction hash binding and mandatory OCR review PASS');
assert.deepEqual(call('list_projects').map(p => p.root), ['/projects/smoke']);
const report = call('diagnostics');
assert.equal(report.schema_version, 1);
assert.equal(report.project_open, true);
assert.equal(report.counts.tasks, 2);
assert.equal(report.network_upload, false);
assert.ok(!JSON.stringify(report).includes('浏览器持久项目'));
console.log('WASM canonical redacted diagnostics PASS');
